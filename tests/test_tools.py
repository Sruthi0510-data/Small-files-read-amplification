def test_the_proof_of_work_transcript_covers_all_four_exit_codes():
    payload = json.loads((ROOT / "docs" / "proof-of-work.json").read_text())
    assert {capture["exit_code"] for capture in payload["captures"]} == {0, 2, 3, 4}


def test_the_transcript_shows_both_verdicts_on_the_same_model():
    """A tool that found amplification everywhere would be a tool with a bug."""
    payload = json.loads((ROOT / "docs" / "proof-of-work.json").read_text())
    commands = {capture["command"]: capture["exit_code"] for capture in payload["captures"]}
    assert commands["python3 -m sfa.cli scan"] == 3
    assert commands["python3 -m sfa.cli scan --layout uniform-large"] == 0


def test_every_captured_command_exited_as_the_readme_claims():
    payload = json.loads((ROOT / "docs" / "proof-of-work.json").read_text())
    for capture in payload["captures"]:
        assert capture["exit_code"] == capture["expected_exit_code"], capture["command"]


def test_every_captured_command_carries_a_hash_of_its_untruncated_output():
    payload = json.loads((ROOT / "docs" / "proof-of-work.json").read_text())
    assert all(len(capture["output_sha256"]) == 64 for capture in payload["captures"])


def test_the_transcript_leaks_no_absolute_path():
    svg = (ROOT / "docs" / "img" / "proof-of-work.svg").read_text(encoding="utf-8")
    assert str(ROOT) not in svg and "/usr/bin/python" not in svg


def test_the_transcript_wraps_rather_than_clipping():
    wrapped = capture_terminal._wrap("x" * 300)
    assert len(wrapped) > 1
    assert "".join(row.lstrip() for row in wrapped) == "x" * 300


def test_a_short_line_is_not_wrapped():
    assert capture_terminal._wrap("short") == ["short"]


def test_the_transcript_shows_the_interpreter_by_name_not_by_path():
    assert capture_terminal._display(["/usr/bin/python3", "-m", "sfa.cli"]) == "python3 -m sfa.cli"


def test_a_mismatched_exit_code_is_drawn_as_a_failure():
    rendered = capture_terminal.render(
        [{"command": "demo", "output": "boom", "exit_code": 1, "expected_exit_code": 0,
          "max_lines": 4, "tail_lines": 0}],
        "demo",
    )
    assert capture_terminal.BAD in rendered


def test_the_readme_embeds_both_images():
    text = (ROOT / "README.md").read_text(encoding="utf-8")
    assert "docs/img/proof-of-work.svg" in text
    assert "docs/img/report-summary.png" in text

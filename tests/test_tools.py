"""Tests for the receipts pipeline, the diagram, the report and the transcript.

The tools are the reason the documents can be trusted, so they get the same
treatment as the library.
"""

from __future__ import annotations

import json
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

import build_report  # noqa: E402
import capture_terminal  # noqa: E402
import check_numbers  # noqa: E402
import render_diagrams  # noqa: E402
import render_tables  # noqa: E402

SVG = "{http://www.w3.org/2000/svg}"


@pytest.fixture
def workspace(tmp_path: Path, monkeypatch):
    def _build(metrics, anchors, documents, table_values=None):
        payload = {
            "metrics": metrics,
            "anchors": anchors,
            "checked_documents": list(documents),
            "table_values": table_values or [],
        }
        (tmp_path / "docs").mkdir(exist_ok=True)
        metrics_path = tmp_path / "docs" / "metrics.json"
        metrics_path.write_text(json.dumps(payload), encoding="utf-8")
        for name, text in documents.items():
            path = tmp_path / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        monkeypatch.setattr(check_numbers, "ROOT", tmp_path)
        monkeypatch.setattr(check_numbers, "METRICS_PATH", metrics_path)
        return tmp_path

    return _build


def test_a_current_figure_passes(workspace):
    workspace({"n": 12}, {"n": ["{} rows differ"]}, {"README.md": "12 rows differ."})
    assert check_numbers.main() == 0


def test_a_stale_figure_fails(workspace):
    workspace({"n": 12}, {"n": ["{} rows differ"]}, {"README.md": "19 rows differ."})
    assert check_numbers.main() == 1


def test_an_anchor_without_a_placeholder_is_refused_by_name(workspace, capsys):
    """It used to raise IndexError from inside a regex match, naming nothing."""
    workspace({"n": 12}, {"n": ["fifteen rows"]}, {"README.md": "fifteen rows."})
    assert check_numbers.main() == 1
    assert "guards nothing" in capsys.readouterr().out


def test_a_malformed_anchor_stops_before_the_later_passes(workspace, capsys):
    workspace({"n": 12}, {"n": ["fifteen rows"]}, {"README.md": "nothing here"})
    check_numbers.main()
    out = capsys.readouterr().out
    assert "ANCHOR" in out and "not quoted anywhere" not in out


def test_a_missing_document_fails(workspace):
    workspace({"n": 1}, {"n": ["{} rows"]}, {})
    path = check_numbers.METRICS_PATH
    payload = json.loads(path.read_text())
    payload["checked_documents"] = ["absent.md"]
    path.write_text(json.dumps(payload), encoding="utf-8")
    assert check_numbers.main() == 1


def test_an_unguarded_number_fails(workspace):
    workspace({"n": 12}, {"n": ["{} rows differ"]}, {"README.md": "12 rows differ, and 77 more."})
    assert check_numbers.main() == 1


def test_a_table_value_is_recognised(workspace):
    workspace(
        {"n": 12},
        {"n": ["{} rows differ"]},
        {"README.md": "12 rows differ, and 77 more."},
        table_values=[77],
    )
    assert check_numbers.main() == 0



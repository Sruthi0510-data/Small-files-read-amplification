def test_the_diagram_is_valid_svg_with_a_title_and_description():
    root = ET.parse(ROOT / "docs" / "img" / "where-the-time-goes.svg").getroot()
    assert root.find(f"{SVG}title") is not None and root.find(f"{SVG}desc") is not None


def test_every_text_element_in_the_diagram_sets_its_own_colour():
    for element in ET.parse(ROOT / "docs" / "img" / "where-the-time-goes.svg").getroot().iter(f"{SVG}text"):
        assert element.get("fill")


def test_the_diagram_reads_its_numbers_from_the_metrics():
    """A hand-typed number in a diagram is the one figure nothing re-measures."""
    metrics = dict(json.loads((ROOT / "docs" / "metrics.json").read_text())["metrics"])
    metrics["plan_visible_label"] = "x"
    svg = render_diagrams.where_the_time_goes(metrics)
    assert str(metrics["plan_blind_pct"]) in svg
    assert str(metrics["break_even_mib"]) in svg
    assert f"{metrics['files']:,}" in svg


def test_regenerating_the_diagram_does_not_change_it():
    path = ROOT / "docs" / "img" / "where-the-time-goes.svg"
    before = path.read_text(encoding="utf-8")
    assert render_diagrams.main() == 0
    assert path.read_text(encoding="utf-8") == before



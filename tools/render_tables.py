"""Write the README's data tables from the experiment JSON, between committed markers.

Hand-typed table cells are the largest hole in a receipts mechanism. An anchor
phrase guards a figure quoted in a sentence; a table of thirty numbers is thirty
figures nobody anchored, and the first one to go stale goes stale silently.
"""

from __future__ import annotations

import json
import re
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
EXPERIMENTS = ROOT / "docs" / "experiments"


def _block(name: str, body: str, source: str) -> str:
    return (
        f"<!-- table:{name} generated by tools/render_tables.py from {source} -->\n"
        f"{body}\n"
        f"<!-- /table:{name} -->"
    )


def _payload() -> dict[str, Any]:
    return json.loads((EXPERIMENTS / "exp01.json").read_text())


def compaction_table() -> tuple[str, list[Any]]:
    payload = _payload()
    values: list[Any] = []
    lines = [
        "| target file size | files after | modelled scan | improvement | pays back after | above break-even |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for row in payload["compaction"]:
        payback = "never" if row["payback_scans"] is None else f"{row['payback_scans']:.1f} scans"
        improvement = f"{100 * row['improvement']:.1f}"
        scan = f"{row['scan_ms']:,.0f}"
        values.extend([row["target_kib"], row["files"], scan, improvement])
        if row["payback_scans"] is not None:
            values.append(f"{row['payback_scans']:.1f}")
        lines.append(
            f"| {row['target_kib']:,} KiB | {row['files']:,} | {scan} ms | {improvement}% | "
            f"{payback} | {'yes' if row['above_break_even'] else 'no'} |"
        )
    return _block("compaction", "\n".join(lines), "exp01.json"), values


def profiles_table() -> tuple[str, list[Any]]:
    payload = _payload()
    values: list[Any] = []
    lines = [
        "| storage and engine | cost per file | throughput | break-even file | invisible to the plan |",
        "| --- | --- | --- | --- | --- |",
    ]
    for row in payload["profiles"]:
        per_file = f"{row['per_file_ms']:.1f}"
        throughput = f"{row['throughput_mib_per_s']:,.0f}"
        break_even = f"{row['break_even_mib']:.1f}"
        blind = f"{100 * row['blind_share']:.1f}"
        values.extend([per_file, throughput, break_even, blind])
        lines.append(
            f"| `{row['profile']}` | {per_file} ms | {throughput} MiB/s | {break_even} MiB | {blind}% |"
        )
    return _block("profiles", "\n".join(lines), "exp01.json"), values


def table_values() -> list[Any]:
    values: list[Any] = []
    for builder in (compaction_table, profiles_table):
        _, produced = builder()
        values.extend(produced)
    return values


def main() -> int:
    text = README.read_text(encoding="utf-8")
    replaced = 0
    for name, builder in (("compaction", compaction_table), ("profiles", profiles_table)):
        block, _ = builder()
        pattern = re.compile(rf"<!-- table:{name}.*?-->.*?<!-- /table:{name} -->", re.DOTALL)
        if not pattern.search(text):
            print(f"no marker block for {name!r} in README.md")
            return 1
        text = pattern.sub(lambda _match, block=block: block, text)
        replaced += 1
    README.write_text(text, encoding="utf-8")
    print(f"rewrote {replaced} generated table block(s) in README.md")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
